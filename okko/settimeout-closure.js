/**
 * Что выведет код и почему? (замыкание + event loop)
 *
 * Вопрос часто дают, чтобы проверить:
 * - что замыкание "смотрит" на переменную, а не копирует значение
 * - что setTimeout(..., 0) выполняется ПОСЛЕ текущего синхронного кода
 */

let x = 10;

setTimeout(() => {
  console.log(x);
}, 0);

x = 20;

// =============================================================================
// Ответ:
// =============================================================================
// Выведет: 20
//
// Почему:
// - Колбэк setTimeout замыкает переменную x (ссылку на неё), а не значение 10.
// - setTimeout(..., 0) ставит колбэк в очередь макрозадач.
// - Сначала выполняется весь текущий синхронный код, включая `x = 20`.
// - Потом event loop берёт макрозадачу, и console.log читает текущее значение x => 20.


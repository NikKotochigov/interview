/**
 * Задача (по скрину):
 *
 * Есть функция asyncAuth(cb), которая принимает функцию-обработчик (callback),
 * в которую может быть передана ошибка (1-м аргументом) или "результат" (дальше).
 * Это классический callback-API в стиле Node.js: cb(err, data).
 *
 * 1) Написать функцию auth(), которая вызывает asyncAuth, но возвращает Promise
 *    (то есть "промисифицировать" asyncAuth).
 * 2) На базе auth() написать функцию tryAuth(n), которая при ошибке делает
 *    дополнительные n попыток, чтобы получить результат.
 *
 * Ниже — одно из типовых решений.
 */

// -----------------------------------------------------------------------------
// 0) Для примера: заглушка asyncAuth(cb)
// В реальной задаче asyncAuth уже дана — эту часть можно удалить.
// -----------------------------------------------------------------------------

function asyncAuth(cb) {
  setTimeout(() => {
    const ok = Math.random() > 0.6; // иногда "падает"
    if (!ok) cb(new Error("Auth failed"));
    else cb(null, { token: "token_" + Math.random().toString(16).slice(2) });
  }, 50);
}

// -----------------------------------------------------------------------------
// 1) auth() — promisyfy callback API
// -----------------------------------------------------------------------------

function auth() {
  return new Promise((resolve, reject) => {
    asyncAuth((err, result) => {
      if (err) reject(err);
      else resolve(result);
    });
  });
}

// -----------------------------------------------------------------------------
// 2) tryAuth(n) — retry: при ошибке делаем ещё n попыток
// -----------------------------------------------------------------------------
// Важно: "n дополнительных попыток" = максимум (1 + n) вызовов auth().
// Например: tryAuth(0) — один вызов без ретраев.

async function tryAuth(n) {
  let attempt = 0;
  let lastError;

  while (attempt <= n) {
    try {
      return await auth();
    } catch (e) {
      lastError = e;
      attempt += 1;
    }
  }

  throw lastError;
}


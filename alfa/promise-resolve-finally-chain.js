/**
 * Задача: цепочка Promise — throw, catch + return, finally (аргументы), вложенный Promise.resolve.
 *
 * Вывод в консоль (по порядку): 2, undefined, 1
 */

// =============================================================================
// Исходный код (как на скрине)
// =============================================================================

const run = () =>
  Promise.resolve(1)
    .then((x) => x + 1) // 2
    .then((x) => {
      throw x;
    }) // rejection с причиной 2
    .then((x) => console.log(x)) // пропускается
    .catch((err) => {
      console.log(err); // 2
      return 10; // цепочка снова fulfilled, дальше идёт значение 10
    })
    .finally((res) => console.log(res)) // finally вызывается без аргументов → undefined
    .then((x) => Promise.resolve(1)) // x === 10, возвращается промис → значение 1
    .catch((err) => console.log(err))
    .then((x) => console.log(x)); // 1

// =============================================================================
// Разбор
// =============================================================================
//
// — После throw следующий .then не выполняется; срабатывает .catch.
// — return 10 в .catch восстанавливает fulfilled; в следующий .then передаётся 10 (в коде не используется).
// — У .finally(onFinally) колбэк вызывается БЕЗ аргументов (res всегда undefined); значение до finally
//   пробрасывается дальше, если finally не бросает ошибку и не возвращает отклонённый промис.
// — Последний .then получает 1 из Promise.resolve(1).


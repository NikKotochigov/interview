// =============================================================================
// Условие задачи (Codewars 6 kyu — Find the unique number)
// =============================================================================
//
// Дано:
//   - массив arr, все элементы одинаковы, кроме одного
//
// Вернуть:
//   - единственное уникальное число (тип сохранить: 2, не "2")
//
// Примеры:
//   [1, 1, 1, 2, 1, 1]     →  2
//   [0, 0, 0.55, 0, 0]     →  0.55
//
// Сложность:
//   Время:  O(n)
//   Память: O(n) — подсчёт; findUniqFast: O(1)
//
// Ошибка в варианте с Object.entries:
//   ключи объекта всегда строки → result === "2", а не 2
//   тесты Codewars: findUniq(...) === 2  (строгое сравнение)
//
// --- вариант 1: подсчёт + find (тип сохраняется) ---

function findUniq(arr) {
  const count = {};

  for (const x of arr) {
    count[x] = (count[x] ?? 0) + 1;
  }

  return arr.find((x) => count[x] === 1);
}

// --- вариант 2: O(n), без Map/объекта — быстрее на огромных массивах ---
// По первым трём элементам понимаем, какое значение «массовое»,
// затем один проход find.

function findUniqFast(arr) {
  const bulk = arr[0] === arr[1] || arr[0] === arr[2] ? arr[0] : arr[1];
  return arr.find((x) => x !== bulk);
}

console.log(findUniq([1, 1, 1, 2, 1, 1])); // 2
console.log(findUniq([0, 0, 0.55, 0, 0])); // 0.55
console.log(findUniqFast([1, 1, 1, 2, 1, 1])); // 2

module.exports = { findUniq, findUniqFast };

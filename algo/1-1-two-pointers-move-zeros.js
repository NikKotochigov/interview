// =============================================================================
// Условие задачи (Codewars 6 kyu — Move Zeros)
// =============================================================================
//
// Дано:
//   - массив arr (числа и другие типы)
//
// Вернуть:
//   - тот же массив in-place: все элементы со значением 0 — в конец
//   - порядок остальных элементов сохранить
//   - false, "", null и т.д. не считаются нулями — только строго x === 0
//
// Примеры:
//   [1, 0, 1, 2, 0, 1, 3]              → [1, 1, 2, 1, 3, 0, 0]
//   [false, 1, 0, 1, 2, 0, 1, 3, 'a']  → [false, 1, 1, 2, 1, 3, 'a', 0, 0]
//
// Сложность:
//   Время:  O(n)
//   Память: O(1)
//
// Алгоритм: два указателя (in-place).
//   write — куда пишем следующий ненулевой элемент
//   проходим arr, ненули копируем в начало, хвост заполняем нулями

function moveZeros(arr) {
  let write = 0;

  for (let i = 0; i < arr.length; i++) {
    if (arr[i] !== 0) {
      arr[write++] = arr[i];
    }
  }

  while (write < arr.length) {
    arr[write++] = 0;
  }

  return arr;
}

// --- примеры ---

console.log(moveZeros([1, 0, 1, 2, 0, 1, 3])); // [1, 1, 2, 1, 3, 0, 0]
console.log(moveZeros([false, 1, 0, 1, 2, 0, 1, 3, 'a'])); // [false, 1, 1, 2, 1, 3, 'a', 0, 0]

module.exports = { moveZeros };

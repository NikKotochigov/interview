// =============================================================================
// Условие задачи (Codewars 4 kyu — Snail / Spiral Matrix)
// =============================================================================
//
// Дано:
//   - квадратная матрица n×n
//
// Вернуть:
//   - массив элементов в порядке обхода по спирали по часовой стрелке
//     от внешнего кольца к центру
//
// Пример:
//   [[1,2,3],[4,5,6],[7,8,9]]  →  [1,2,3,6,9,8,7,4,5]
//   [[1,2,3],[8,9,4],[7,6,5]]  →  [1,2,3,4,5,6,7,8,9]
//
// Сложность:
//   Время:  O(n²) — каждый элемент один раз
//   Память: O(n²) — массив результата
//
// Алгоритм: четыре границы top/bottom/left/right.
//
//   [1, 2, 3]     шаг 1 → вправо по верху:     1, 2, 3
//   [4, 5, 6]     шаг 2 → вниз по правому:         6, 9
//   [7, 8, 9]     шаг 3 → влево по низу:       8, 7
//                 шаг 4 → вверх по левому:    4
//                 центр (1×1):                5
//
// Алгоритм: четыре границы-указателя сжимают «кольцо» после каждого витка.

function snailSort(matrix) {
    // Пустая матрица или пустая строка
    if (!matrix.length || !matrix[0].length) return [];

    const result = [];

    // Границы текущего слоя (ещё не обойденного кольца)
    let top = 0;                    // верхняя строка
    let bottom = matrix.length - 1; // нижняя строка
    let left = 0;                   // левый столбец
    let right = matrix[0].length - 1; // правый столбец

    // Пока осталась хотя бы одна строка и один столбец
    while (top <= bottom && left <= right) {

        // 1. Верхняя строка: слева направо (→)
        //    top=0: берём [1,2,3]
        for (let col = left; col <= right; col++) {
            result.push(matrix[top][col]);
        }
        top++; // верх «снят», следующий виток начинается со строки ниже

        // 2. Правый столбец: сверху вниз (↓)
        //    начинаем с row=top, чтобы не взять угол дважды (он уже в шаге 1)
        //    right=2: берём 6, потом 9
        for (let row = top; row <= bottom; row++) {
            result.push(matrix[row][right]);
        }
        right--; // правый край снят

        // 3. Нижняя строка: справа налево (←)
        //    проверка top <= bottom: если осталась одна строка, низ уже обошли в шаге 1
        //    bottom=2: берём 8, 7
        if (top <= bottom) {
            for (let col = right; col >= left; col--) {
                result.push(matrix[bottom][col]);
            }
            bottom--; // низ снят
        }

        // 4. Левый столбец: снизу вверх (↑)
        //    left <= right: если остался один столбец, левый уже обошли в шаге 2
        //    left=0: берём 4
        if (left <= right) {
            for (let row = bottom; row >= top; row--) {
                result.push(matrix[row][left]);
            }
            left++; // левый край снят
        }

        // Кольцо снято → top/bottom/left/right сузились, цикл берёт следующий слой
        // Для 3×3 после 1-го витка: top=1, bottom=1, left=1, right=1 → остается [5]
        // Второй виток: один элемент 5, цикл завершается
    }

    return result;
}

// --- примеры ---

console.log(
    snailSort([
        [1, 2, 3],
        [4, 5, 6],
        [7, 8, 9],
    ])
); // [1, 2, 3, 6, 9, 8, 7, 4, 5]

console.log(
    snailSort([
        [1, 2, 3],
        [8, 9, 4],
        [7, 6, 5],
    ])
); // [1, 2, 3, 4, 5, 6, 7, 8, 9]

module.exports = { snailSort };

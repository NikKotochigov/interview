// =============================================================================
// Условие задачи (Codewars — Find the Outlier)
// =============================================================================
//
// Дано:
//   - массив целых (могут быть отрицательными)
//   - все числа одной чётности, кроме одного outlier
//
// Вернуть:
//   - значение outlier
//
// Примеры:
//   [2, 4, 0, 100, 4, 11, 2602, 36]  →  11
//   [160, 3, 1719, 19, 11, 13, -21]  →  160
//
// Сложность:
//   Время:  O(n)
//   Память: O(1)
//
// Алгоритм:
//   По первым 3 элементам понимаем, кого мало (чётных или нечётных).
//   Один проход — находим единственный элемент нужной чётности.
//
// Почему хватает 3 элементов: outlier только один,
//   в любой тройке всегда ≥ 2 числа «основной» чётности.

function findOutlier(integers) {
  const evenInFirstThree = integers.slice(0, 3).filter((n) => n % 2 === 0).length;
  const outlierIsOdd = evenInFirstThree >= 2;

  return integers.find((n) =>
    outlierIsOdd ? n % 2 !== 0 : n % 2 === 0
  );
}

// --- примеры ---

console.log(findOutlier([2, 4, 0, 100, 4, 11, 2602, 36])); // 11
console.log(findOutlier([160, 3, 1719, 19, 11, 13, -21])); // 160

module.exports = { findOutlier };

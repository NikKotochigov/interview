// =============================================================================
// Условие задачи 3 — max и min в несортированном массиве
// =============================================================================
//
// Дано: несортированный массив чисел (не пустой).
// Вернуть: { max, min }
//
// Идея: max/min = arr[0], один проход, сравнение с arr[i].
//
// Сложность: O(n) время, O(1) память

/**
 * @param {number[]} arr
 * @returns {{ max: number, min: number }}
 */
function findMaxMin(arr) {
  let max = arr[0];
  let min = arr[0];

  for (let i = 1; i < arr.length; i++) {
    if (arr[i] > max) {
      max = arr[i];
    } else if (arr[i] < min) {
      min = arr[i];
    }
  }

  return { max, min };
}

// --- пример ---
console.log(findMaxMin([1, 2, 3, 4, 100])); // { max: 100, min: 1 }

// =============================================================================
// Условие задачи 4 — накопительные (cumulative) суммы
// =============================================================================
//
// Дано: [a, b, c, ...]
// Вернуть: [a, a+b, a+b+c, ...]
//
// Идея: result[0] = arr[0], дальше result[i] = arr[i] + result[i-1]
//
// Сложность: O(n) время, O(n) память — массив результата

/**
 * @param {number[]} list
 * @returns {number[]}
 */
function cumulativeSum(list) {
  const result = [list[0]];

  for (let i = 1; i < list.length; i++) {
    result.push(list[i] + result[i - 1]);
  }

  return result;
}

// --- пример ---
console.log(cumulativeSum([1, 3, 5, 7])); // [1, 4, 9, 16]

// =============================================================================
// Условие задачи 5 — все значения-дубликаты
// =============================================================================
//
// Дано: массив целых (могут повторяться).
// Вернуть: массив уникальных значений, которые встречались > 1 раза,
//           или [] если дубликатов нет.
//
// Идея: хеш-счётчик observed[val]. При втором появлении — push в dupesArray.
//
// Сложность: O(n) время, O(n) память

/**
 * @param {number[]} arr
 * @returns {number[]}
 */
function findAllDupes(arr) {
  const observed = {};
  const dupesArray = [];

  for (let i = 0; i < arr.length; i++) {
    if (observed[arr[i]]) {
      if (observed[arr[i]] === 1) {
        dupesArray.push(arr[i]);
      }
      observed[arr[i]] = observed[arr[i]] + 1;
    } else {
      observed[arr[i]] = 1;
    }
  }

  return dupesArray;
}

// --- пример ---
console.log(findAllDupes([1, 1, 2, 3, 4, 5, 6, 7, 8, 6, 6, 7, 7, 7, 10, 10])); // [1, 6, 7, 10]

// =============================================================================
// Условие задачи 6 — убрать дубликаты (отсортированный массив)
// =============================================================================
//
// Дано: отсортированный массив целых.
// Вернуть: новый массив без дубликатов (каждое значение один раз).
//
// Идея: смотреть на предыдущий элемент. Если arr[i] !== previous — push.
// Без sort: можно через хеш, как в задачах 2 и 5.
//
// Сложность: O(n) время, O(n) память — новый массив результата

/**
 * @param {number[]} arr — отсортированный
 * @returns {number[]}
 */
function removeDupesSorted(arr) {
  const result = [];
  let previous = arr[0];
  result[0] = previous;

  for (let i = 0; i < arr.length; i++) {
    if (arr[i] !== previous) {
      result.push(arr[i]);
    }
    previous = arr[i];
  }

  return result;
}

// --- пример ---
console.log(removeDupesSorted([1, 1, 1, 1, 1, 1, 1])); // [1]

// =============================================================================
// Условие задачи 7 — пары с заданной суммой
// =============================================================================
//
// Дано: массив целых (без дубликатов), целое value.
// Вернуть: массив пар [[a,b], ...] где a + b === value, или [].
//
// Идея: для arr[i] ищем complement = value - arr[i] в хеше sumsLookup.
//       Перед добавлением в хеш проверяем, видели ли complement.
//
// Сложность: O(n) время, O(n) память

/**
 * @param {number[]} arr
 * @param {number} value
 * @returns {number[][]}
 */
function findSumPairs(arr, value) {
  const sumsLookup = {};
  const output = [];

  for (let i = 0; i < arr.length; i++) {
    const targetVal = value - arr[i];

    if (sumsLookup[targetVal]) {
      output.push([arr[i], targetVal]);
    }

    sumsLookup[arr[i]] = true;
  }

  return output;
}

// --- пример --- (массив без дубликатов)
console.log(findSumPairs([1, 5, 6, 0], 6)); // [[5, 1], [0, 6]]


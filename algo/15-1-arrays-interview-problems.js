// =============================================================================
// Условие задачи 1 — пропущенное число (1..100)
// =============================================================================
//
// Дано: отсортированный массив уникальных чисел из диапазона 1..100,
//       ровно одно число пропущено.
// Вернуть: целое — пропущенное число.
//
// Идея: один проход. Если arr[i] + 1 !== arr[i + 1], пропуск — arr[i] + 1.
// Край: если пропущена 1 — arr[0] !== 1.
// Пропущена 100 — только если массив из 99 чисел и последний 99:
//   if (arr.length === 99 && arr[98] === 99) return 100;
//
// Сложность: O(n) время, O(1) память

/**
 * @param {number[]} arr — отсортированный, числа 1..100, одно пропущено
 * @returns {number|false}
 */
function findMissingNum(arr) {
  if (arr[0] !== 1) return 1;

  for (let i = 0; i < arr.length - 1; i++) {
    if (arr[i] + 1 !== arr[i + 1]) {
      return arr[i] + 1;
    }
  }

  return false;
}

// --- пример ---
console.log(findMissingNum([1, 2, 3, 4, 5, 6, 7, 8, 10])); // 9

// =============================================================================
// Условие задачи 2 — число с одним дубликатом
// =============================================================================
//
// Дано: массив целых (есть ровно один дубликат — одно число 2 раза).
// Вернуть: это число, или false если дубликатов нет.
//
// Идея: хеш observed. Видели — return, иначе записать.
//
// Сложность: O(n) время, O(n) память

/**
 * @param {number[]} arr
 * @returns {number|false}
 */
function findDupe(arr) {
  const observed = {};

  for (let i = 0; i < arr.length; i++) {
    if (observed[arr[i]]) {
      return arr[i];
    }
    observed[arr[i]] = true;
  }

  return false;
}

// --- пример ---
console.log(findDupe([1, 2, 3, 4, 5, 6, 7, 7, 8, 6, 10])); // 7


// =============================================================================
// Условие задачи (LeetCode 15 — 3Sum)
// =============================================================================
//
// Дано:
//   - массив nums целых чисел
//
// Вернуть:
//   - все уникальные тройки [a, b, c] из nums (три разных индекса),
//     такие что a + b + c === 0
//   - в ответе не должно быть повторяющихся троек
//     (например [-1,0,1] и [-1,0,1] — одна и та же)
//
// Примеры:
//   [-1, 0, 1, 2, -1, -4]  →  [[-1,-1,2], [-1,0,1]]
//   [0, 1, 1]              →  []
//   [0, 0, 0]              →  [[0,0,0]]
//
// Паттерн: два указателя (two pointers) после сортировки
//
// Сложность:
//   Время:  O(n²) — сорт O(n log n) + для каждого i проход l,r
//   Память: O(1) без учёта ответа (или O(n) под сортировку в JS)
//
// Идея:
//   1) сортируем — чтобы двигать указатели предсказуемо
//   2) фиксируем nums[i] — «первое число» тройки
//   3) в оставшемся отрезке [i+1 .. n-1] ищем пару с суммой -nums[i]
//      указателями l (слева) и r (справа), как в Two Sum II

/**
 * @param {number[]} nums
 * @returns {number[][]}
 */
function threeSum(nums) {
  // без сортировки два указателя не работают: непонятно, куда сдвигать l/r
  nums.sort((a, b) => a - b);

  const result = [];

  // i — индекс первого числа; нужны ещё минимум два справа → i <= n-3
  for (let i = 0; i < nums.length - 2; i++) {
    // nums[i] === nums[i-1] → та же тройка, что уже искали → пропуск
    if (i > 0 && nums[i] === nums[i - 1]) {
      continue;
    }

    // ищем пару: nums[l] + nums[r] === -nums[i]
    let l = i + 1;
    let r = nums.length - 1;

    while (l < r) {
      const sum = nums[i] + nums[l] + nums[r];

      if (sum === 0) {
        result.push([nums[i], nums[l], nums[r]]);

        // нашли тройку — сдвигаем оба указателя
        // и пропускаем дубликаты l/r, иначе в ответ попадут одинаковые тройки
        while (l < r && nums[l] === nums[l + 1]) {
          l++;
        }
        while (l < r && nums[r] === nums[r - 1]) {
          r--;
        }
        l++;
        r--;
      } else if (sum < 0) {
        // сумма мала → нужно число побольше → двигаем l вправо
        l++;
      } else {
        // сумма велика → нужно поменьше → двигаем r влево
        r--;
      }
    }
  }

  return result;
}

// --- примеры ---

console.log(threeSum([-1, 0, 1, 2, -1, -4])); // [[-1,-1,2],[-1,0,1]]
console.log(threeSum([0, 1, 1])); // []
console.log(threeSum([0, 0, 0])); // [[0,0,0]]

// --- по шагам: [-1, 0, 1, 2, -1, -4] ---
//
// после sort: [-4, -1, -1, 0, 1, 2]
//
// i=0, nums[i]=-4, l=1, r=5
//   суммы не 0 → троек с -4 нет
//
// i=1, nums[i]=-1, l=2, r=5
//   -1 + (-1) + 2 = 0  →  [-1,-1,2]
//   l=3, r=4
//   -1 + 0 + 1 = 0     →  [-1,0,1]
//
// i=2, nums[i]=-1 === nums[1] → skip (дубликат первого числа)
//
// ответ: [[-1,-1,2], [-1,0,1]]

module.exports = { threeSum };

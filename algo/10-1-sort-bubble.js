// =============================================================================
// Условие задачи (сортировка — пузырьковая)
// =============================================================================
//
// Дано:
//   - массив arr чисел
//
// Вернуть:
//   - тот же массив, отсортированный по возрастанию (in-place)
//
// Пример:
//   [5, 2, 11, 1, 10]  →  [1, 2, 5, 10, 11]
//
// Сложность:
//   Время:  O(n²)
//   Память: O(1)
//
// Алгоритм: bubble sort — соседи меняются местами.
//
// Пример [5, 2, 11, 1, 10]:
//
// i=0 | j=0..3: 5↔2, 5↔1, 11↔1, 11↔10 → [2, 5, 1, 10, 11]
// i=1 | j=0..2: 2↔1           → [2, 1, 5, 10, 11]
// i=2 | j=0..1: 2↔1           → [1, 2, 5, 10, 11]
// i=3 | j=0:    без обменов   → [1, 2, 5, 10, 11] ✓

const sortBubble = (arr) => {
    const n = arr.length;

    for (let i = 0; i < n - 1; i++) {
        for (let j = 0; j < n - 1 - i; j++) {
            if (arr[j] > arr[j + 1]) {
                let temp = arr[j];
                arr[j] = arr[j + 1];
                arr[j + 1] = temp;
            }
        }

        console.log(arr)
    }

    return arr
}

const arr = [5, 2, 11, 1, 10];

console.log(sortBubble(arr));

// =============================================================================
// Условие задачи (Яндекс.Контест — динамический список)
// =============================================================================
//
// Дано:
//   - q запросов (позиции нумеруются с 1)
//
// Типы запросов:
//   1 x y — вставить y после позиции x; x=0 → вставить в начало
//   2 x   — вывести элемент на позиции x
//   3 x   — удалить элемент на позиции x
//
// Вернуть:
//   - для всех запросов типа 2 — ответы построчно (stdout)
//
// Пример:
//   1 0 5  →  [5]
//   2 1    →  5
//   3 1    →  []
//   1 0 6  →  [6]
//   1 0 7  →  [7, 6]
//   2 2    →  6
//   1 1 5  →  [7, 5, 6]
//   2 2    →  5
//
// Ограничение: q ≤ 5000 → массив + splice/unshift достаточно.
//
// Сложность:
//   Время:  O(q · n) в худшем — splice/unshift O(n)
//   Память: O(n) — хранение списка
//
// Пример из условия:
//
// 1 0 5     → [5]
// 2 1       → 5
// 3 1       → []
// 1 0 6     → [6]
// 1 0 7     → [7, 6]
// 2 2       → 6
// 1 1 5     → после 1-й (7): [7, 5, 6]
// 2 2       → 5
//
// === Как читать ввод в Яндекс.Контест / Node.js ===
// Переменной input в редакторе НЕТ — её создаёшь сам из stdin:
//
//   const input = require('fs').readFileSync(0, 'utf8').trim().split('\n');
//
// 0 — это stdin (то, что в поле «Ввод»). input[0] — первая строка, input[1] — вторая...

const input = require('fs').readFileSync(0, 'utf8').trim().split('\n');
const q = Number(input[0]);
const list = [];
const answers = [];

for (let i = 1; i <= q; i++) {
    const parts = input[i].split(' ').map(Number);
    const type = parts[0];

    if (type === 1) {
        const x = parts[1];
        const y = parts[2];

        if (x === 0) {
            list.unshift(y);
        } else {
            list.splice(x, 0, y); // после x-й → вставка на индекс x (0-based)
        }
    } else if (type === 2) {
        const x = parts[1];
        answers.push(String(list[x - 1]));
    } else {
        const x = parts[1];
        list.splice(x - 1, 1);
    }
}

console.log(answers.join('\n'));

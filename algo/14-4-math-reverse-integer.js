// =============================================================================
// Условие задачи (LeetCode 7 — Reverse Integer)
// =============================================================================
//
// Дано:
//   - знаковое 32-bit целое x
//
// Вернуть:
//   - x с цифрами в обратном порядке
//   - если результат не влезает в [-2^31, 2^31 - 1] → 0
//
// Примеры:
//   123          →  321
//   -123         →  -321
//   120          →  21   (ноль в конце исчезает)
//   1534236469   →  0    (переполнение int32)
//
// Сложность:
//   Время:  O(d) — d = количество цифр
//   Память: O(1)
//
// Идея (собес, простой вариант для JS):
//   в цикле: rev = rev * 10 + последняя цифра x, x без последней цифры
//   в конце проверяем диапазон int32

/**
 * @param {number} x
 * @returns {number}
 */
function reverse(x) {
  let rev = 0;

  while (x !== 0) {
    // x % 10 — последняя цифра (для отрицательных тоже с минусом: -123 → -3)
    rev = rev * 10 + (x % 10);

    // убираем последнюю цифру; | 0 отбрасывает дробную часть
    x = (x / 10) | 0;
  }

  // разворот дал число вне 32-bit → по условию возвращаем 0
  if (rev < -(2 ** 31) || rev > 2 ** 31 - 1) {
    return 0;
  }

  return rev;
}

// --- примеры ---

console.log(reverse(123)); // 321
console.log(reverse(-123)); // -321
console.log(reverse(120)); // 21
console.log(reverse(1534236469)); // 0

// --- по шагам: x = 123 ---
//
//   x=123  digit=3   rev=3    x=12
//   x=12   digit=2   rev=32   x=1
//   x=1    digit=1   rev=321  x=0 → стоп
//
// --- по шагам: x = -123 ---
//
//   x=-123 digit=-3  rev=-3   x=-12
//   x=-12  digit=-2  rev=-32  x=-1
//   x=-1   digit=-1  rev=-321 x=0

module.exports = { reverse };

// =============================================================================
// Условие задачи (LeetCode 45 — Jump Game II)
// =============================================================================
//
// Дано:
//   - массив nums: nums[i] — макс. длина прыжка вперёд с индекса i
//   - гарантируется, что индекс n-1 достижим
//
// Вернуть:
//   - минимальное число прыжков с индекса 0 до n-1
//
// Примеры:
//   [2, 3, 1, 1, 4]  →  2  (0→1→4)
//   [2, 3, 0, 1, 4]  →  2
//
// Сложность:
//   Время:  O(n)
//   Память: O(1)
//
// Алгоритм: жадный (greedy).
//   end — правый край текущего «окна» (доступно в рамках уже сделанных прыжков)
//   farthest — самая дальняя точка, до которой можно дойти из этого окна
//   дошли до end → нужен ещё один прыжок, end = farthest

function jump(nums) {
  let jumps = 0;
  let end = 0;       // конец текущего окна
  let farthest = 0;  // максимум, куда можно дойти в этом окне

  // последний индекс не обрабатываем — мы уже на финише, когда i === n-1
  for (let i = 0; i < nums.length - 1; i++) {
    farthest = Math.max(farthest, i + nums[i]);

    if (i === end) {
      jumps++;
      end = farthest;
    }
  }

  return jumps;
}

// --- примеры ---

console.log(jump([2, 3, 1, 1, 4])); // 2  (0→1→4)
console.log(jump([2, 3, 0, 1, 4])); // 2

module.exports = { jump };

/**
 * Задача: цепочка Promise — порядок then/catch и повторный throw (Сбер / подготовка).
 */

// =============================================================================
// Задача
// =============================================================================
//
// Исходный код:
//
//   new Promise(res => res())
//     .then(() => console.log(1))
//     .catch(() => console.log(2))
//     .then(() => {
//       throw new Error('Ошибка')
//     })
//     .catch(err => {
//       console.log(4)
//       throw err
//       console.log(5)
//     })
//     .then(() => console.log(6))
//     .catch(() => console.log(7))
//
// Что будет выведено в консоль (по порядку): 1, 4, 7
//
// — 2 не выводится: .catch срабатывает только при отклонении предыдущего звена; после then с log(1)
//   промис выполнен успешно, этот catch пропускается (не вызывается).
// — 5 не выводится: код после throw в том же блоке недостижим.
// — 6 не выводится: после catch с throw err промис снова в состоянии rejection; следующий .then
//   для успеха не выполняется при ошибке — ошибка «пробрасывается» к следующему .catch.

// =============================================================================
// Исправление и объяснение
// =============================================================================
//
// Ошибки в поведении обычно не «исправляют» — важно понимать модель:
// — fulfilled → идёт следующий .then; .catch пропускается до ближайшего rejection.
// — rejection → пропускаются .then до ближайшего .catch.
// — если в .catch сделать return (или не бросать ошибку), цепочка снова становится fulfilled.
// — если в .catch снова throw — цепочка остаётся rejected (как здесь перед log(7)).

const run = () =>
  new Promise((res) => res())
    .then(() => console.log(1))
    .catch(() => console.log(2))
    .then(() => {
      throw new Error('Ошибка');
    })
    .catch((err) => {
      console.log(4);
      throw err;
      console.log(5);
    })
    .then(() => console.log(6))
    .catch(() => console.log(7));


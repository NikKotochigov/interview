//
// Исходный код:
//
//   function sayHi() {
//     console.log(name); // undefined
//     console.log(age); // ReferenceError: Cannot access 'age' before initialization
//     var name = "Lydia";
//     let age = 21;
//   }
//
//   sayHi();
//
// Что будет выведено:
// — в консоль сначала: undefined (переменная name из var «поднята», значение ещё не присвоено);
// — затем выполнение прерывается: ReferenceError: Cannot access 'age' before initialization
//   (у let/const до строки объявления действует временная мёртвая зона — читать age нельзя).

// =============================================================================
// Исправление и объяснение
// =============================================================================
//
// var объявление поднимается в начало функции и даёт name === undefined до присваивания "Lydia".
// let не даёт обратиться к переменной до объявления — это TDZ, не «undefined как у var».
//
// Исправление: объявлять и присваивать до использования или перенести console.log ниже.

function sayHiFixed() {
  var name = 'Lydia';
  let age = 21;
  console.log(name); // Lydia
  console.log(age); // 21
}


/**
 * Задача: event loop — sync, microtasks (Promise), macrotasks (setTimeout) (Сбер / подготовка).
 */

// =============================================================================
// Задача
// =============================================================================
//
// Исходный код:
//
//   setTimeout(function() {
//     console.log(2)
//   })
//
//   Promise.resolve(3).then(console.log)
//
//   console.log(4)
//
//   setTimeout(function() {
//     console.log(5)
//   }, 0)
//
//   console.log(6)
//
// Что будет выведено в консоль (порядок чисел): 4, 6, 3, 2, 5

// =============================================================================
// Исправление и объяснение
// =============================================================================
//
// 1) Сначала выполняется весь синхронный код по порядку: регистрируются два setTimeout
//    (задержка по умолчанию как 0), ставится микрозадача у Promise, печатается 4, потом 6.
// 2) Синхронный стек пуст — обрабатывается очередь микрозадач: .then выводит 3
//    (аргумент в then — console.log, ему передаётся разрешённое значение 3).
// 3) Затем макрозадачи (таймеры) в порядке постановки: сначала колбэк с 2, потом с 5.
//
// Итог: sync (4, 6) → microtasks (3) → macrotasks (2, 5).

function run() {
  setTimeout(function () {
    console.log(2);
  });

  Promise.resolve(3).then(console.log);

  console.log(4);

  setTimeout(function () {
    console.log(5);
  }, 0);

  console.log(6);
}


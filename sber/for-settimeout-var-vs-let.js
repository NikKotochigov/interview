/**
 * Задача: for + setTimeout — var (одна переменная) vs let (блок на итерацию) (Сбер / подготовка).
 */

// =============================================================================
// Задача
// =============================================================================
//
// Фрагмент 1:
//
//   for (var i = 0; i < 3; i++) {
//     setTimeout(() => console.log(i), 1);
//   }
//
// Что будет выведено: 3, 3, 3 (часто в одной строке без переносов в зависимости от консоли)
//
// Фрагмент 2:
//
//   for (let i = 0; i < 3; i++) {
//     setTimeout(() => console.log(i), 1);
//   }
//
// Что будет выведено: 0, 1, 2 (порядок строк может слегка отличаться по таймингу, значения такие)

// =============================================================================
// Исправление и объяснение
// =============================================================================
//
// var: одна переменная i на всю функцию/скрипт; цикл успевает закончиться до таймеров, i становится 3.
// Все колбэки setTimeout смотрят на одну и ту же i → три раза 3.
//
// let: на каждой итерации for создаётся новая привязка i в области блока цикла; замыкание хранит
// своё значение на момент итерации → 0, 1, 2.
//
// Классическое «исправление» для var без смены на let — IIFE или отдельный аргумент в setTimeout:
// setTimeout((j) => console.log(j), 1, i) на каждой итерации (передаёт текущее значение).

function demoVar() {
  for (var i = 0; i < 3; i++) {
    setTimeout(() => console.log(i), 1);
  }
}

function demoLet() {
  for (let i = 0; i < 3; i++) {
    setTimeout(() => console.log(i), 1);
  }
}

// Альтернатива для var: замыкание с немедленным значением
function demoVarIife() {
  for (var i = 0; i < 3; i++) {
    ((k) => {
      setTimeout(() => console.log(k), 1);
    })(i);
  }
}

// demoVar();   // 3 3 3
// demoLet();   // 0 1 2
// demoVarIife(); // 0 1 2

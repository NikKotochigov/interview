// Написать функцию, которая отфильтрует дубликаты в массиве (не использовать Set)
//
//   const array = [8, 4, 4, 2, 2, 1, 2, 2, 2, 4, 4, 4];
//
//   function removeDuplicates(arr) {
//
//   }
//
//   console.log(removeDuplicates(array)); // => [8, 4, 2, 1]

// =============================================================================
// Решение (оптимальное по времени для сохранения порядка)
// =============================================================================
//
// Один проход по массиву: O(n) по времени, O(n) доп. памяти — для задачи «уникальные с сохранением
// порядка первых вхождений» это оптимально (нельзя быстрее в худшем случае: нужно хотя бы прочитать n).
//
// Хеш «уже видели» вместо Set: объект без прототипа (Object.create(null)), чтобы не цепляться
// к унаследованным ключам вроде toString. Для чисел ключи приводятся к строке — для таких массивов ок.
//
// Медленнее: arr.filter((x, i) => arr.indexOf(x) === i) — O(n²).
// sort + проход — ломает исходный порядок.

/**
 * @param {number[]} arr
 * @returns {number[]}
 */
function removeDuplicates(arr) {
  const seen = {};
  const out = [];
  for (let i = 0; i < arr.length; i++) {
    if (seen[arr[i]]) continue;
    seen[arr[i]] = true;
    out.push(arr[i]);
  }
  return out;
}


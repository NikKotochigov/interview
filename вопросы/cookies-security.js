/**
 * Cookie security — простыми словами и на примерах
 *
 * -----------------------------------------------------------------------------
 * 0) Что такое cookie «по-человечески»
 * -----------------------------------------------------------------------------
 *
 * Cookie — это маленькая запись (name=value), которую браузер хранит для сайта.
 * Потом браузер автоматически прикладывает эти cookie к запросам на этот сайт.
 *
 * Важно:
 * - Cookie — это НЕ один «файл». Это набор записей.
 * - У каждой записи свои атрибуты: Domain, Path, HttpOnly, Secure, SameSite, Max-Age/Expires…
 * - Одна строка `Set-Cookie` в ответе сервера = одна cookie.
 * - В одном ответе может быть несколько заголовков `Set-Cookie`.
 *
 * -----------------------------------------------------------------------------
 * 1) Как браузер выбирает, какие cookie отправлять
 * -----------------------------------------------------------------------------
 *
 * Упрощённо браузер отправляет cookie, если совпали условия:
 * - **Domain**: для какого домена cookie действует
 * - **Path**: для какого пути cookie действует (например, / или /admin)
 * - **Secure**: только по HTTPS
 * - **SameSite**: ограничения на «чужие» (cross-site) запросы
 * - Плюс: cookie не просрочена (Max-Age/Expires)
 *
 * Пример установки двух cookie:
 *
 *   Set-Cookie: sid=abc; Path=/; HttpOnly; Secure; SameSite=Lax
 *   Set-Cookie: theme=dark; Path=/settings
 *
 * Тогда запросы:
 * - на `GET https://example.com/` отправят: sid=abc
 * - на `GET https://example.com/settings/profile` отправят: sid=abc и theme=dark
 *
 * -----------------------------------------------------------------------------
 * 2) document.cookie — что там видно (и почему это важно)
 * -----------------------------------------------------------------------------
 *
 * `document.cookie` показывает только:
 * - cookie, которые подходят под текущий Path
 * - cookie без HttpOnly
 *
 * Поэтому сессионную cookie почти всегда делают HttpOnly — чтобы XSS не мог просто
 * прочитать её и унести «ключ от аккаунта».
 *
 * -----------------------------------------------------------------------------
 * 3) Главные флаги cookie и зачем они
 * -----------------------------------------------------------------------------
 *
 * ### HttpOnly
 * - **Что делает**: JS на странице НЕ может читать/писать эту cookie через `document.cookie`.
 * - **От чего защищает**: от кражи cookie через XSS (прямая кража `document.cookie`).
 * - **От чего НЕ защищает**: если у тебя XSS, злоумышленник всё равно может делать запросы
 *   от имени пользователя (браузер сам приложит cookie к запросам). Это уже про действия,
 *   а не про «вытащить значение».
 *
 * ### Secure
 * - **Что делает**: cookie отправляется только по HTTPS.
 * - **От чего защищает**: от перехвата в сети при HTTP (Wi‑Fi, прокси, MitM).
 * - **Практика**: для сессий Secure — почти must-have (в проде должен быть HTTPS).
 *
 * ### SameSite
 * - **Что делает**: ограничивает отправку cookie в cross-site запросах (важно для CSRF).
 * - **Режимы**:
 *   - `Strict`: почти не отправляет cookie при переходах с других сайтов (максимальная защита,
 *     но может ломать UX: переходы по внешним ссылкам, SSO и т.п.).
 *   - `Lax`: разумный баланс. Обычно cookie не уйдёт в «чужом» POST/iframe, но уйдёт при
 *     top-level навигации на сайт (например, обычный клик по ссылке).
 *   - `None`: cookie будет отправляться и в third-party контексте, но **требует Secure**.
 *
 * ### Path
 * - **Что делает**: где cookie видна/отправляется по пути.
 * - **Зачем**: уменьшает «зону поражения». Например, админскую cookie можно ограничить `/admin`.
 * - **Важно**: Path — на каждую cookie отдельно (глобально «на все сразу» не задаётся).
 *
 * ### Domain
 * - **Что делает**: расширяет действие cookie на поддомены.
 * - Пример: `Domain=example.com` позволит отправлять cookie и на `api.example.com`, и на `www.example.com`.
 * - **Риск**: чем шире Domain, тем больше мест, где cookie может утечь/быть перезаписана.
 *
 * -----------------------------------------------------------------------------
 * 4) Типовые уязвимости вокруг cookie (и как защищаться)
 * -----------------------------------------------------------------------------
 *
 * Ниже — самые частые сценарии на собеседованиях и в реальности.
 *
 * A) XSS → кража cookie (session hijacking)
 * ---------------------------------------
 * Сценарий:
 * - На странице есть XSS.
 * - Скрипт читает `document.cookie` и отправляет атакующему.
 *
 * Защита:
 * - **HttpOnly** на сессионной cookie (тогда прочитать её из JS нельзя).
 * - Плюс: лечить XSS (экранирование/санитизация/CSP) — HttpOnly не «чинит» XSS.
 *
 * B) CSRF → действия от имени пользователя
 * ---------------------------------------
 * Сценарий:
 * - Пользователь залогинен на `bank.example`.
 * - Он открывает злой сайт, который делает POST на `bank.example/transfer`.
 * - Браузер автоматически прикладывает cookie сессии → запрос выглядит «как от пользователя».
 *
 * Защита:
 * - **SameSite=Lax/Strict** (часто достаточно Lax).
 * - **CSRF-токены** (особенно если SameSite=None или сложные потоки/интеграции).
 * - Проверка `Origin`/`Referer` (как дополнительный слой, с нюансами).
 *
 * C) Перехват cookie в сети (если нет HTTPS)
 * -----------------------------------------
 * Сценарий:
 * - Cookie ушла по HTTP.
 * - Её можно подсмотреть в сети и использовать для входа.
 *
 * Защита:
 * - **HTTPS везде** + **Secure**.
 * - HSTS (чтобы браузер сам принуждал HTTPS).
 *
 * D) Session fixation (фиксация сессии)
 * ------------------------------------
 * Сценарий:
 * - Атакующий добивается, чтобы жертва использовала заранее известный идентификатор сессии.
 * - Потом атакующий использует этот sid и получает доступ.
 *
 * Защита:
 * - Регенерировать идентификатор сессии после логина/повышения прав.
 * - Не принимать sid из URL, не отдавать его в открытых местах.
 *
 * E) Слишком широкий Domain / уязвимый поддомен → компрометация
 * ------------------------------------------------------------
 * Сценарий:
 * - Cookie поставили на `Domain=example.com` (для всех поддоменов).
 * - На одном из поддоменов (`promo.example.com`) нашли XSS или его вообще захватили (subdomain takeover).
 * - Атакующий может ставить/перезаписывать cookie для общего домена или воровать данные, которые доступны на том поддомене.
 *
 * Защита:
 * - Делать Domain максимально узким (часто вообще не указывать Domain → cookie будет host-only).
 * - Следить за безопасностью всех поддоменов, если всё же нужен общий Domain.
 *
 * F) «Path confusion» и дубли cookie
 * ---------------------------------
 * Нюанс:
 * - Можно иметь две cookie с одним именем, но разными Path.
 * - Это иногда приводит к багам или уязвимостям, когда сервер берёт «не ту» cookie.
 *
 * Пример:
 *   Set-Cookie: sid=AAA; Path=/
 *   Set-Cookie: sid=BBB; Path=/admin
 *
 * На `/admin` браузер отправит обе: `sid=BBB; sid=AAA` (порядок может отличаться).
 * Если бэкенд парсит криво и берёт «первую попавшуюся», можно получить неожиданный sid.
 *
 * Защита:
 * - Не плодить одинаковые имена cookie на разных Path без крайней необходимости.
 * - Парсить Cookie заголовок корректно и детерминированно.
 *
 * -----------------------------------------------------------------------------
 * 5) «Золотой» пример для сессионной cookie (часто на практике)
 * -----------------------------------------------------------------------------
 *
 * Типичная сессионная cookie:
 *
 *   Set-Cookie: sid=<random>; Path=/; HttpOnly; Secure; SameSite=Lax
 *
 * Пояснение:
 * - `HttpOnly`: XSS не прочитает sid из `document.cookie`
 * - `Secure`: sid не утечёт по HTTP
 * - `SameSite=Lax`: снижает CSRF для большинства обычных сценариев
 * - `Path=/`: сессия работает по всему сайту
 *
 * -----------------------------------------------------------------------------
 * 6) Пример «что увидит document.cookie» для понимания
 * -----------------------------------------------------------------------------
 *
 * Допустим сервер выставил:
 *
 *   Set-Cookie: sid=abc; Path=/; HttpOnly; Secure; SameSite=Lax
 *   Set-Cookie: lang=ru; Path=/
 *   Set-Cookie: theme=dark; Path=/settings
 *
 * Тогда:
 * - если ты на странице `/`:
 *     document.cookie === "lang=ru"
 *
 * - если ты на странице `/settings/profile`:
 *     document.cookie === "theme=dark; lang=ru"
 *
 * (sid не виден, потому что HttpOnly)
 *
 * -----------------------------------------------------------------------------
 * 7) Частые ошибки (короткий чеклист)
 * -----------------------------------------------------------------------------
 *
 * - Сессионная cookie без HttpOnly → XSS = лёгкая кража сессии.
 * - Сессионная cookie без Secure на проде → риск утечки при любом HTTP участке.
 * - SameSite=None без Secure → современные браузеры откажутся/ограничат такую cookie.
 * - Domain слишком широкий → один слабый поддомен может «потянуть» весь домен.
 * - Секреты в cookie (например, пароль/ключ API) → почти всегда плохая идея.
 */


// =============================================================================
// 1) Инкапсуляция (Encapsulation)
// =============================================================================
// Идея: скрываем внутреннее состояние/детали и даём наружу понятный интерфейс.
// Плюс: внешний код не зависит от того, как всё устроено внутри.

class Counter {
  #value = 0; // приватное поле (доступно только внутри класса)

  inc() {
    this.#value += 1;
    return this.#value;
  }

  getValue() {
    return this.#value;
  }
}


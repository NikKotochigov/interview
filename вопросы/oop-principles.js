// c.inc(); // 1
// c.getValue(); // 1
// c.#value; // SyntaxError: приватное поле нельзя трогать снаружи

// =============================================================================
// 2) Наследование (Inheritance)
// =============================================================================
// Идея: "переиспользуем" поведение базового класса и расширяем его.
// Плюс: меньше копипасты. Минус: сильная связность, часто проще композиция.

class Animal {
  constructor(name) {
    this.name = name;
  }
  speak() {
    return `${this.name} makes a sound`;
  }
}

class Dog extends Animal {
  speak() {
    return `${this.name} barks`;
  }
}

// new Dog('Rex').speak() -> "Rex barks"

// =============================================================================
// 3) Полиморфизм (Polymorphism)
// =============================================================================
// Идея: разные объекты поддерживают один и тот же "интерфейс" (например, метод speak),
// и код, который их использует, не обязан знать конкретный тип.

function makeItSpeak(animal) {
  // Важно: нам всё равно, Dog это или Animal или Cat, лишь бы был speak()
  return animal.speak();
}

class Cat extends Animal {
  speak() {
    return `${this.name} meows`;
  }
}

// makeItSpeak(new Dog('Rex')) -> "Rex barks"
// makeItSpeak(new Cat('Murka')) -> "Murka meows"

// =============================================================================
// 4) Абстракция (Abstraction)
// =============================================================================
// Идея: показываем наружу только важное, а детали реализации прячем.
// На практике: работаем с "контрактом" (что умеет объект), а не с тем, как он это делает.

// Пример: платежи. Внешнему коду важно "pay(amount)", а как именно платим — не важно.

class CardPayment {
  pay(amount) {
    return `Paid ${amount} by card`;
  }
}

class CryptoPayment {
  pay(amount) {
    return `Paid ${amount} by crypto`;
  }
}

function checkout(paymentProvider, amount) {
  // Абстракция: мы ожидаем контракт "pay(amount)"
  return paymentProvider.pay(amount);
}

// checkout(new CardPayment(), 100) -> "Paid 100 by card"
// checkout(new CryptoPayment(), 100) -> "Paid 100 by crypto"


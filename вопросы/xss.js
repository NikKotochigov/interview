// =============================================================================
// 8.2 DOM-based XSS: данные из URL → DOM
// =============================================================================

// BAD:
// const hash = decodeURIComponent(location.hash.slice(1));
// document.body.insertAdjacentHTML('beforeend', hash);

// GOOD: не интерпретировать hash как HTML; максимум — текст или заранее известные ключи
function showHashAsText() {
  if (typeof location === 'undefined') return '';
  const raw = location.hash.slice(1);
  return decodeURIComponent(raw); // дальше только textContent, не innerHTML
}

// =============================================================================
// 8.3 Атрибут href / src — контекст URL (javascript:, data:, и т.д.)
// =============================================================================
//
// Простыми словами: вы рисуете ссылку «куда перейти». Пользователь подсовывает не
// https://другой-сайт.ru, а строку вида javascript:… — для браузера это тоже «адрес»,
// только вместо перехода на сайт выполнится код при клике.

// BAD:
// a.setAttribute('href', userControlledString);
// userControlledString = 'javascript:alert(1)' — при клике выполнится

/** Разрешить только http(s) для ссылок, иначе вернуть безопасный fallback. */
function safeHref(userUrl, fallback = '#') {
  try {
    const u = new URL(userUrl, 'https://example.invalid');
    if (u.protocol === 'http:' || u.protocol === 'https:') return u.toString();
  } catch {
    /* невалидный URL */
  }
  return fallback;
}


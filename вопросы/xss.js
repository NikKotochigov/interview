// Задача: показать имя пользователя на странице.
//
// Шаг 1. Пользователь (или ссылка в письме) передал «имя»:
//   нормально:     Мария
//   злоумышленник: </p><img src=x onerror="alert('меня выполнили')">
//
// Шаг 2а. ОПАСНО — innerHTML склеивает имя с разметкой:
//   el.innerHTML = '<p>Привет, ' + имя + '</p>';
//   Браузер читает HTML: закрывается </p>, появляется <img …>, срабатывает onerror.
//
// Шаг 2б. ЛУЧШЕ — textContent: браузер не парсит имя как теги, это просто буквы на экране:
//   renderPlainText(el, имя);  // см. функцию ниже
//
// Итог: одна и та же строка-«имя» — в одном случае это атака, в другом просто текст.


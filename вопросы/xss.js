/**
 * XSS (Cross-Site Scripting) — подробно и простыми словами
 *
 * -----------------------------------------------------------------------------
 * 0. Сначала на примерах — совсем простой язык
 * -----------------------------------------------------------------------------
 *
 * Ситуация «как в жизни»
 * -----------------------
 * Сайт хочет показать фразу: «Привет, ИМЯ», где ИМЯ пришло от пользователя (из формы,
 * из адреса в браузере, из комментария — неважно).
 *
 * Программист вставляет ИМЯ прямо в HTML-страницу «как есть».
 *
 *   Обычный человек написал имя: Мария          → на экране просто текст «Мария». Ок.
 *   Злоумышленник «имя» подставил так, что там есть угловые скобки и команды для
 *   браузера (теги, обработчики вроде onerror=…). Браузер не спрашивает «это добрый
 *   человек или нет» — он видит разметку и может выполнить встроенный код.
 *
 * В чём суть в одном предложении
 * -------------------------------
 * XSS — это когда чужая строка попала на страницу так, что браузер воспринял её не
 * как «просто текст для человека», а как часть страницы/кода и что-то выполнил.
 *
 * Маленький пример «на пальцах» (не код, а логика)
 * -----------------------------------------------
 * Ты хотел вывести на сайте слово с угловыми скобками: <пример>
 *
 * Если вставить это в HTML без специальной обработки, символ < может означать «начало
 * тега», а не «символ для показа». Злоумышленник подсовывает не слово, а «ломаный» кусок,
 * после которого браузер думает: «вот тут закончился текст, дальше идёт команда».
 *
 * Три вида — одной фразой каждый
 * ------------------------------
 * - Отражённый: жертва открыла «кривую» ссылку один раз — вредоносный кусок прилетел
 *   в запросе и тут же попал в ответ страницы.
 * - Сохранённый: кто-то один раз сохранил вредоносный комментарий в базу — дальше
 *   каждый читатель страницы подставляет себе эту «мину».
 * - DOM-based: сервер отдал нормальную страницу, а JavaScript на клиенте сам взял
 *   текст из адреса и небезопасно вставил в страницу (часто через innerHTML).
 *
 * Что делать «в голове» при разработке
 * ------------------------------------
 * Всё от пользователя по умолчанию — это текст, который нужно ПОКАЗАТЬ, а не «кусок
 * HTML для браузера». Для ссылок — проверять, что это обычный http/https, а не
 * javascript:… и т.п. Не превращать чужие строки в программу (eval, «умный» innerHTML).
 *
 * -----------------------------------------------------------------------------
 * 1. Что это такое
 * -----------------------------------------------------------------------------
 *
 * XSS — это класс уязвимостей веб-приложений, когда злоумышленник внедряет в страницу
 * (или в ответ сервера) исполняемый в браузере жертвы код — обычно JavaScript — так,
 * что браузер считает его «своим» и выполняет в контексте вашего сайта.
 *
 * Ключевая идея: браузер не различает «хороший» HTML/JS от «плохого» по смыслу — он
 * просто парсит разметку и исполняет скрипты по правилам. Если в вывод попала строка
 * от пользователя без экранирования, она может стать частью разметки или кода.
 *
 * Название «Cross-Site» историческое: часто атака идёт через другой «контекст» или
 * подстановку данных с другого источника, но для практики важнее не этимология, а то,
 * что код выполняется в сессии жертвы на вашем домене.
 *
 * -----------------------------------------------------------------------------
 * 2. Почему это опасно (не «просто alert»)
 * -----------------------------------------------------------------------------
 *
 * В контексте вашего origin скрипт атакующего может:
 *
 * - Читать DOM страницы (в т.ч. персональные данные, отрендеренные на клиенте).
 * - Делать запросы от имени пользователя (cookie с запросом уходит автоматически,
 *   если нет жёстких ограничений — см. ниже про SameSite и fetch credentials).
 * - Перехватывать ввод (кейлоггинг форм), менять интерфейс (фишинг «внутри» сайта).
 * - Вызвать действия от имени пользователя, если нет дополнительной защиты (CSRF-токены
 *   и т.д. — отдельная тема, но XSS часто обходит ожидания «пользователь сам нажал»).
 *
 * Даже «безопасный» на первый взгляд alert(1) на собеседовании — лишь доказательство
 * контроля над исполнением; в реальной атаке полезная нагрузка другая.
 *
 * -----------------------------------------------------------------------------
 * 3. Основные виды XSS
 * -----------------------------------------------------------------------------
 *
 * A) Reflected (отражённый / неперсистентный)
 *    Вредоносная строка приходит в запросе (URL, форма) и сервер (или шаблон)
 *    «отражает» её в ответе без экранирования. Жертва открывает специально сформированную
 *    ссылку или отправляет форму — скрипт выполняется один раз в этом ответе.
 *
 * B) Stored (сохранённый / персистентный)
 *    Данные сохраняются в БД/файле/комментарии и при каждом просмотре подставляются в HTML.
 *    Затрагивается больше пользователей; ссылку кликать не обязательно — достаточно зайти
 *    на страницу с компрометированным контентом.
 *
 * C) DOM-based
 *    Сервер может отдавать «чистый» статический HTML, но клиентский JS читает
 *    location.hash, query-параметры, postMessage и т.п. и небезопасно вставляет их
 *    в DOM (innerHTML, document.write, шаблоны без экранирования). Уязвимость целиком
 *    в браузере; бэкенд формально «ни при чём», но риск тот же.
 *
 * -----------------------------------------------------------------------------
 * 4. Типичные причины появления
 * -----------------------------------------------------------------------------
 *
 * - Конкатенация пользовательского ввода в HTML на сервере или в шаблоне без экранирования
 *   под контекст (атрибут, текст, URL, JS-строка — у каждого контекста свои правила).
 * - Небезопасный innerHTML, outerHTML, insertAdjacentHTML с данными из URL/хранилища/API.
 * - eval, new Function, setTimeout/setInterval со строкой из внешних данных.
 * - Некорректная «санитизация» (самописные фильтры легко обойти).
 * - Устаревшие или слишком доверчивые библиотеки (например, парсеры HTML в JS).
 *
 * -----------------------------------------------------------------------------
 * 5. Что НЕ является полной защитой само по себе
 * -----------------------------------------------------------------------------
 *
 * - «Мы используем React» — по умолчанию React экранирует текст в JSX, но dangerouslySetInnerHTML,
 *   href={userInput}, передача HTML из API в сыром виде и ошибки в SSR всё равно дают XSS.
 * - «У нас HTTPS» — шифрование канала не мешает серверу отдать вредоносный HTML жертве.
 * - «Скрытые поля / POST» — отражённый XSS не обязан быть в GET; важна подстановка в ответ.
 *
 * -----------------------------------------------------------------------------
 * 6. Направления защиты (краткий чеклист для интервью и практики)
 * -----------------------------------------------------------------------------
 *
 * 1) По умолчанию трактовать весь ввод как данные, а не как разметку: выводить текст
 *    через API фреймворка/шаблонизатора, который экранирует под HTML-контекст.
 *
 * 2) Если HTML от пользователя необходим — санитизация проверенной библиотекой
 *    (например, DOMPurify на клиенте; на сервере — аналог с учётом политики тегов),
 *    плюс жёсткий allowlist тегов/атрибутов, без «чёрных списков» как единственной линии.
 *
 * 3) Content-Security-Policy (CSP): ограничить источники скриптов, инлайн-скрипты,
 *    eval; это сильно снижает ущерб даже при одной дырке в экранировании.
 *
 * 4) Cookie: HttpOnly (недоступны из document.cookie для JS), Secure, SameSite=Lax/Strict
 *    где уместно — уменьшают кражу сессии простым скриптом, но не заменяют экранирование.
 *
 * 5) Везде, где вставляется пользовательская строка в URL, onclick, style, SVG —
 *    отдельные правила экранирования; «закодировали в HTML» недостаточно для href="...".
 *
 * 6) Регулярный security-ревью мест с innerHTML, шаблонами из строк, rich-text редакторами.
 *
 * -----------------------------------------------------------------------------
 * 7. Связь с другими темами
 * -----------------------------------------------------------------------------
 *
 * - CSRF: заставить браузер отправить запрос; XSS часто усиливает сценарии или обходит UI.
 * - Clickjacking: обычно борются X-Frame-Options / CSP frame-ancestors — ортогонально XSS,
 *   но оба про доверие к отображению и действиям пользователя.
 *
 * Итог для собеседования: XSS — это выполнение контролируемого атакующим кода в браузере
 * жертвы в контексте вашего приложения из-за небезопасной обработки данных при выводе
 * или в клиентском DOM; защита — экранирование по контексту, минимизация опасных API,
 * CSP и грамотная работа с cookies, плюс санитизация там, где HTML неизбежен.
 *
 * -----------------------------------------------------------------------------
 * 8. Примеры кода (ниже в файле)
 * -----------------------------------------------------------------------------
 *
 * Ниже — учебные фрагменты: «BAD» показывает типичную уязвимость (не копировать в прод),
 * «GOOD» — безопасные альтернативы. Уязвимые строки не выполняются при импорте/запуске файла.
 */


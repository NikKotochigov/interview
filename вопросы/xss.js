// 8.1 innerHTML / вставка «сырого» HTML из внешнего источника
// =============================================================================

// BAD (браузер парсит строку как HTML; скрипт/обработчики могут выполниться):
// const q = new URLSearchParams(location.search).get('name') ?? '';
// el.innerHTML = `<p>Привет, ${q}</p>`;
// Пример «имени» в адресе (учебный): имя заканчивает <p> и вставляет картинку с onerror

/** Безопасно вывести произвольный текст как содержимое узла (не как разметку). */
function renderPlainText(el, userText) {
  el.textContent = userText;
}


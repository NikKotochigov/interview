/**
 * Дженерики (Generics) в TypeScript — кратко + примеры
 *
 * Идея: дженерик — это "параметр типа", который позволяет писать код,
 * который работает с разными типами, но сохраняет типобезопасность.
 *
 * Пример из жизни: "функция identity возвращает то, что ей передали"
 * без потери типа.
 */

// =============================================================================
// 0) Базовая интуиция: "тип — как параметр функции"
// =============================================================================

function identity<T>(value: T): T {
  return value;
}

const a = identity(123); // number
const b = identity("hi"); // string

// Можно явно указать T (редко нужно, чаще TS выведет сам):
const c = identity<boolean>(true); // boolean

// =============================================================================
// 1) Несколько параметров типов
// =============================================================================

function pair<A, B>(first: A, second: B): [A, B] {
  return [first, second];
}

const p = pair("id", 42); // [string, number]

// =============================================================================
// 2) Дженерики в type/interface
// =============================================================================

type Dict<T> = Record<string, T>;

const numbers: Dict<number> = { x: 1, y: 2 };
const strings: Dict<string> = { a: "1" };

interface ApiResponse<T> {
  data: T;
  error?: string;
}

const resp1: ApiResponse<{ id: number }> = { data: { id: 1 } };
const resp2: ApiResponse<string[]> = { data: ["a", "b"], error: undefined };

// =============================================================================
// 3) Ограничения (constraints) через extends
// =============================================================================

// Хотим .length, значит требуем "объект с length"
function lengthOf<T extends { length: number }>(value: T): number {
  return value.length;
}

lengthOf("hello"); // ok
lengthOf([1, 2, 3]); // ok
// lengthOf(123); // ошибка: у number нет length

// =============================================================================
// 4) keyof + безопасный доступ к свойствам
// =============================================================================

function getProp<T extends object, K extends keyof T>(obj: T, key: K): T[K] {
  return obj[key];
}

const user = { id: 1, name: "Ada" };
const userId = getProp(user, "id"); // number
// getProp(user, "age"); // ошибка: "age" не keyof user

// =============================================================================
// 5) Значения разного типа в словаре: не "T", а объединение
// =============================================================================

const mixed: Record<string, string | number> = {
  key1: "value1",
  key2: 42,
};

// =============================================================================
// 6) Дженерик по умолчанию (default type)
// =============================================================================

type Box<T = string> = { value: T };

const bx1: Box = { value: "ok" }; // T = string по умолчанию
const bx2: Box<number> = { value: 123 };

// =============================================================================
// 7) Условные типы + infer (часто в интервью)
// =============================================================================

// "Достать" тип элемента массива
type ElementOf<T> = T extends (infer U)[] ? U : never;

type E1 = ElementOf<number[]>; // number
type E2 = ElementOf<string[]>; // string

// "Достать" тип, который возвращает функция
type Return<T> = T extends (...args: any[]) => infer R ? R : never;

type R1 = Return<() => Promise<number>>; // Promise<number>

// =============================================================================
// 8) Частые ошибки/вопросы
// =============================================================================
// - Record<string, <T>> — синтаксически неверно, нужно Record<string, T>
// - Один T не может быть одновременно string и number (если только T = string | number)
// - unknown безопаснее, чем any, если "любой тип"

// =============================================================================
// Быстрые ответы для интервью (1–2 строки)
// =============================================================================
// - Дженерики: параметризуем тип, чтобы переиспользовать код без потери типов.
// - Constraints: ограничиваем T (T extends ...), чтобы гарантировать нужные поля.
// - keyof: получаем множество ключей объекта и делаем доступ безопасным.
// - conditional + infer: "вычисляем" типы (вытащить элемент массива, return type и т.п.).


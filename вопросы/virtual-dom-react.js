/**
 * Virtual DOM в React — что это и как это связано с «оптимизацией»
 *
 * -----------------------------------------------------------------------------
 * 1. Что такое Virtual DOM (в терминах React)
 * -----------------------------------------------------------------------------
 *
 * Это не отдельная «вторая копия» страницы в памяти как у браузера. React описывает UI
 * как дерево простых объектов — элементы React (React elements): тип, пропсы, дети.
 * После вызова компонентов получается описание «как должно выглядеть дерево».
 *
 * Реальный DOM — тяжёлый, с большим API; менять его часто и точечно «вручную» легко
 * ошибиться. React держит это описание в виде лёгких JS-объектов и на его основе решает,
 * какие минимальные операции сделать с настоящим DOM.
 *
 * -----------------------------------------------------------------------------
 * 2. Главная идея оптимизации: не трогать DOM лишний раз
 * -----------------------------------------------------------------------------
 *
 * Полная перерисовка всей страницы при каждом изменении стейта была бы дорогой. React
 * после обновления строит новое виртуальное дерево (новое описание) и сравнивает его
 * со старым — процесс называют reconciliation (согласование). На выходе — набор
 * конкретных изменений: что добавить, что удалить, какие пропсы у узла поменять.
 *
 * То есть Virtual DOM — это формат, удобный для СРАВНЕНИЯ; выигрыш в том, что дифф
 * делается на быстрых JS-структурах, а к DOM идут уже пакетированные, локальные правки.
 *
 * -----------------------------------------------------------------------------
 * 3. Fiber и два этапа (упрощённо)
 * -----------------------------------------------------------------------------
 *
 * В современном React (Fiber) работа разделена грубо на:
 *
 * - Render phase: React вызывает компоненты, строит/обновляет дерево элементов,
 *   помечает, что поменялось. Эту фазу можно прерывать и продолжать (concurrent mode),
 *   чтобы не блокировать основной поток надолго.
 *
 * - Commit phase: применение изменений к реальному DOM (и вызовы useLayoutEffect и т.д.).
 *   Эта фаза синхронна и короче по замыслу — пользователь видит согласованный результат.
 *
 * Virtual DOM / дерево элементов участвует в render phase; commit трогает уже DOM.
 *
 * -----------------------------------------------------------------------------
 * 4. Как React понимает, что именно обновить (reconciliation)
 * -----------------------------------------------------------------------------
 *
 * - Сравнение идёт по типам узлов: если на месте был <div>, а стал <span> — поддерево
 *   пересоздаётся, а не «патчится» по кускам внутри старого узла.
 *
 * - Для списков однотипных элементов критичен key: React сопоставляет старые и новые
 *   элементы по key. Плохой key (например, индекс при сортировке) ломает сопоставление —
 *   лишние пересоздания и сброс локального состояния в дочерних компонентах.
 *
 * - memo / PureComponent / useMemo / useCallback не про Virtual DOM напрямую: они
 *   уменьшают работу ДО построения дерева (пропустить лишние рендеры компонентов), что
 *   косвенно уменьшает и объём диффа.
 *
 * -----------------------------------------------------------------------------
 * 5. Батчинг обновлений
 * -----------------------------------------------------------------------------
 *
 * Несколько setState подряд в одном событии (или в React 18+ часто в асинхронных местах)
 * React может объединить в одно обновление — одна проходка рендера вместо нескольких.
 * Это снижает число проходов reconciliation и коммитов.
 *
 * -----------------------------------------------------------------------------
 * 6. Что Virtual DOM НЕ делает
 * -----------------------------------------------------------------------------
 *
 * - Это не «всегда быстрее, чем прямой DOM»: для очень простых сценариев ручной DOM
 *   может быть тоньше; выигрыш React — в предсказуемости и масштабировании сложного UI.
 *
 * - Сам по себе Virtual DOM не заменяет алгоритмические оптимизации: тяжёлые вычисления
 *   в рендере всё равно нужно мемоизировать (useMemo), большие списки — виртуализировать
 *   (windowing), тяжёлые эффекты — выносить из синхронного рендера.
 *
 * -----------------------------------------------------------------------------
 * Итог одной фразой
 * -----------------------------------------------------------------------------
 *
 * React использует лёгкое дерево описания UI, чтобы диффить изменения в JS и применять
 * к реальному DOM минимальный набор операций; плюс Fiber и батчинг уменьшают лишнюю
 * работу и блокировки основного потока.
 */

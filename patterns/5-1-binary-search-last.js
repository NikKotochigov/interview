//              │ можно разделить элементы на «хорошие»      │
//              │ и «плохие»? (монотонное свойство)           │
//              └──────────────┬──────────────────────────────┘
//                    ДА       │       НЕТ
//         ┌───────────────────┘       └──────────────┐
//         ▼                                          ▼
//  ┌─────────────────────────────┐            другая тема
//  │ в ответе нужен диапазон     │            (не бинарный поиск)
//  │ или доп. подготовка?        │
//  └──────────────┬──────────────┘
//           ДА    │    НЕТ
//    ┌────────────┘    └─────────────┐
//    ▼                               ▼
// ┌──────────────────────┐    ┌─────────────────────┐
// │ двойной бинарный     │    │ базовый бинарный    │
// │ поиск                │    │ поиск               │
// └──────────┬───────────┘    └─────────────────────┘
//            │                  один target, любой индекс
//            ▼                  while (l <= r), mid, < / >
//  5-2-binary-search-range.js
//  searchFirst + searchLast → [first, last]
//
//  ЭТОТ ФАЙЛ (5-1) — половина «двойного»: только searchLast
//
// «Хорошие / плохие»: при sorted nums и predicate «nums[i] >= target»
//   слева плохо, справа хорошо → можно жать границу бинарным поиском.
//
// =============================================================================

// Паттерн: бинарный поиск — последнее вхождение (часть «двойного»)
//
// Отличие от «найти любой target»:
//   при nums[m] <= target двигаем l = m (ищем максимальный индекс с value <= target)
//   в конце l — кандидат на последнее вхождение.
//
// Полуинтервал [l, r): r = nums.length, цикл while (r - l > 1).

// =============================================================================
// Условие задачи (идея: последнее вхождение в отсортированном массиве)
// =============================================================================
//
// Дано:
//   - nums — отсортирован по возрастанию (могут быть дубликаты)
//   - target — искомое значение
//
// Нужно вернуть:
//   - индекс ПОСЛЕДНЕГО вхождения target в nums
//   - если target нет — -1
//
// Примеры:
//   nums = [1, 2, 2, 2, 3],  target = 2  →  3
//   nums = [1, 2, 3],        target = 4  →  -1
//   nums = [5, 5, 5],        target = 5  →  2
//
// Связь с LC:
//   Find First and Last Position (34) — этот код = «last»,
//   для «first» условие: nums[m] >= target → r = m.
//
// =============================================================================

/**
 * Индекс последнего вхождения target (отсортированный массив).
 *
 * @param {number[]} nums
 * @param {number} target
 * @returns {number}
 */
function searchLast(nums, target) {
  let l = 0;
  let r = nums.length; // [l, r) — r указывает «за» последний элемент

  while (r - l > 1) {
    const m = l + Math.floor((r - l) / 2);

    if (nums[m] <= target) {
      // m слишком слева или попали в target — ищем правее (включая m)
      l = m;
    } else {
      // nums[m] > target — ответ только левее m
      r = m;
    }
  }

  return nums[l] === target ? l : -1;
}

// --- пример ---
//
// nums = [1, 2, 2, 2, 3], target = 2
//
// l=0 r=5 → m=2, nums[2]=2 <= 2 → l=2
// l=2 r=5 → m=3, nums[3]=2 <= 2 → l=3
// l=3 r=5 → m=4, nums[4]=3 > 2  → r=4
// l=3 r=4 → стоп (r-l=1)
// nums[3]===2 → 3
//
console.log(searchLast([1, 2, 2, 2, 3], 2)); // 3
console.log(searchLast([1, 2, 3], 4)); // -1
console.log(searchLast([5, 5, 5], 5)); // 2

// --- зачем r = nums.length, а не length - 1 ---
//
//   Полуинтервал [l, r): r «за» концом — проще не ошибиться с границами.
//   Цикл while (r - l > 1) оставляет один кандидат в l.

module.exports = { searchLast };

// Паттерн: Два указателя (Two Pointers)
//
// Суть: вместо вложенных циклов O(n²) держим два индекса l и r
//       и двигаем их по правилам за один проход O(n).
//
// Варианты:
//   1. С противоположных концов (l=0, r=n-1) — отсортированный массив,
//      пара с заданной суммой, палиндром, контейнер с водой.
//   2. В одну сторону (l, r оба слева или «быстрый/медленный») —
//      удаление дубликатов, sliding window, связный список.
//
// Когда узнаёшь задачу:
//   - массив ОТСОРТИРОВАН (или можно отсортировать);
//   - нужна пара/тройка, сумма, сравнение краёв;
//   - можно «отбрасывать» часть массива, сдвигая l или r.
//
// Ниже — классика: Two Sum II (LeetCode 167) на отсортированном массиве.
// Для НЕотсортированного массива — хеш-таблица (см. algo/15-1-arrays-interview-problems.js).

/**
 * Два указателя с концов: найти индексы двух чисел с суммой target.
 *
 * @param {number[]} nums — отсортирован по возрастанию
 * @param {number} target
 * @returns {number[]} [leftIndex, rightIndex] или [-1, -1]
 */
function twoSum(nums, target) {
  // l — слева (меньшие числа), r — справа (большие)
  let l = 0;
  let r = nums.length - 1;

  while (l < r) {
    const currSum = nums[l] + nums[r];

    if (currSum === target) {
      // нашли пару — возвращаем индексы (не значения)
      return [l, r];
    } else if (currSum > target) {
      // сумма слишком большая → убираем правый (самый большой) элемент
      r--;
    } else {
      // сумма слишком маленькая → берём элемент побольше слева
      l++;
    }
  }

  // пары нет (по условию LeetCode 167 пара всегда есть)
  return [-1, -1];
}

// --- пример ---
// nums = [2, 7, 11, 15], target = 9
// l=0,r=3 → 2+15=17 > 9 → r--
// l=0,r=2 → 2+11=13 > 9 → r--
// l=0,r=1 → 2+7=9  → [0, 1]
console.log(twoSum([2, 7, 11, 15], 9)); // [0, 1]

// --- почему это работает (отсортированный массив) ---
//
//   [ 2,  7,  11,  15 ]
//     l              r
//
// Если currSum > target — любая пара с nums[r] только увеличит сумму,
//   значит r не может быть в ответе → r--.
// Если currSum < target — nums[l] слишком мал для текущего r,
//   увеличиваем сумму → l++.
// Каждый шаг сужает поиск — не более n шагов → O(n) время, O(1) память.
//
// Сравнение с хешем (Two Sum I, массив не отсортирован):
//   один проход + объект «видели ли complement» → O(n) время, O(n) память.

module.exports = { twoSum };

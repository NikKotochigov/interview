// Паттерн: монотонный стек (Monotonic Stack)
//
// Стек хранит «кандидатов» на ответ; поддерживаем монотонность
// (здесь: снизу вверх — убывающий стек при обходе справа налево).
//
// См. 6-1-stack-valid-parentheses.js — обычный стек для пар скобок.

// =============================================================================
// Условие задачи (LeetCode 496 / 503 — Next Greater Element)
// =============================================================================
//
// Дано:
//   - массив nums
//
// Нужно вернуть:
//   - массив result той же длины
//   - result[i] — первый элемент СПРАВА от i, который строго больше nums[i]
//   - если такого нет — -1
//
// Примеры:
//   [2, 1, 2, 4, 3]  →  [4, 2, 4, -1, -1]
//   [5, 4, 3, 2, 1]  →  [-1, -1, -1, -1, -1]
//   [1, 3, 4, 2]     →  [3, 4, -1, -1]
//
// Идея (справа налево):
//   стек = элементы справа, для которых мы ещё не нашли «больший слева»
//   перед push снимаем всё <= nums[i] — они не могут быть ответом для левых
//
// Сложность: O(n) время, O(n) память.
//
// =============================================================================

/**
 * @param {number[]} nums
 * @returns {number[]}
 */
function nextGreater(nums) {
  const n = nums.length;
  const stack = [];
  const result = new Array(n).fill(-1);

  for (let i = n - 1; i >= 0; i--) {
    // убираем из стека всё, что не больше nums[i]
    while (stack.length && stack[stack.length - 1] <= nums[i]) {
      stack.pop();
    }

    if (stack.length) {
      result[i] = stack[stack.length - 1];
    }

    stack.push(nums[i]);
  }

  return result;
}

// --- пример: [2, 1, 2, 4, 3] ---
//
// i=4: stack []           → result[4]=-1, push 3
// i=3: pop 3 (3<=4)       → stack [], result[3]=-1, push 4
// i=2: top 4 > 2          → result[2]=4, push 2
// i=1: top 2 > 1          → result[1]=2, push 1
// i=0: pop 1, pop 2, 4>2  → result[0]=4
//
// итог: [4, 2, 4, -1, -1]
//
console.log(nextGreater([2, 1, 2, 4, 3])); // [4, 2, 4, -1, -1]
console.log(nextGreater([5, 4, 3, 2, 1])); // [-1, -1, -1, -1, -1]

module.exports = { nextGreater };

// Паттерн: два указателя / растущее окно — сжатие подряд идущих диапазонов
//
// Задача (идея LeetCode 228 Summary Ranges):
//   отсортированный массив → строки "a" или "a->b" для непрерывных отрезков.
//
// Идея:
//   l — начало текущего отрезка, r — конец (растёт, пока nums[r+1] === nums[r] + 1)
//   записали отрезок → l = r + 1, r = r + 1
//
// Связь с паттернами:
//   2-1-sliding-window.js — окно фиксированной длины k
//   этот файл — окно РАСТЁТ, пока числа идут подряд (+1)
//
// Сложность: O(n) время, O(1) доп. память (без учёта result).

// =============================================================================
// Условие задачи (LeetCode 228 — Summary Ranges)
// =============================================================================
//
// Дано:
//   - массив nums уникальных целых, отсортирован по возрастанию
//
// Нужно вернуть:
//   - минимальный список диапазонов, покрывающих все числа:
//     • одно число → строка "7"
//     • подряд идущие a, a+1, … b → строка "a->b"
//
// Примеры:
//   [0, 1, 2, 4, 5, 7]  →  ["0->2", "4->5", "7"]
//   [0, 2, 3, 4, 6, 8, 9]  →  ["0", "2->4", "6", "8->9"]
//   [-1]  →  ["-1"]
//
// Паттерн по фреймворку (2-1): непересекающиеся окна — каждый элемент
//   в одном отрезке, l/r растут, потом l = r + 1.
//
// =============================================================================

/**
 * @param {number[]} nums — отсортирован
 * @returns {string[]}
 */
function compressRanges(nums) {
  let l = 0; // левая граница отрезка
  let r = 0; // правая граница (двигаем вправо, пока +1)
  const result = [];

  while (l < nums.length) {
    // расширяем r, пока следующий элемент = текущий + 1
    while (r + 1 < nums.length && nums[r] + 1 === nums[r + 1]) {
      r++;
    }

    if (r !== l) {
      // отрезок из нескольких чисел: "0->2"
      result.push(nums[l] + '->' + nums[r]);
    } else {
      // одно число: "7"
      result.push(String(nums[l]));
    }

    // следующий отрезок начинается после r
    l = r + 1;
    r = r + 1;
  }

  return result;
}

/**
 * @param {number[]} nums — отсортирован
 * @returns {string[]}
 */
function compressRanges(nums) {
  let l = 0;
  let r = 0;
  const result = [];

  while (l < nums.length) {
    while (r < nums.length - 1 && nums[r] + 1 === nums[r + 1]) {
      r++;
    }

    if (l === r) {
      result.push(String(nums[l]));
    } else {
      result.push(`${nums[l]}->${nums[r]}`);
    }

    l = r + 1;
    r = r + 1;
  }

  return result;
}

// --- пример ---
//
//   nums = [0, 1, 2, 4, 5, 7]
//
// l=0,r=0 → r растёт до 2 (0,1,2 подряд) → "0->2"
// l=3,r=3 → r до 4 → "4->5"
// l=5,r=5 → одно число → "7"
//
console.log(compressRanges([0, 1, 2, 4, 5, 7])); // ['0->2', '4->5', '7']

// --- визуально ---
//
//   [ 0, 1, 2,  4, 5,  7 ]
//     l───r      l─r     l,r
//
// Внутренний while — «поглощает» все +1 подряд, внешний — старт нового отрезка.

module.exports = { compressRanges };

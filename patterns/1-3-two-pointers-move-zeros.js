// Паттерн: Два указателя — slow / fast (в одну сторону)
//
// Задача (LeetCode 283 Move Zeroes): все нули в конец, порядок
// ненулевых элементов сохранить. Менять массив на месте.
//
// Идея:
//   fast — «сканер», идёт по всему массиву (0 .. n-1)
//   slow — позиция, куда положить следующий ненулевой элемент
//
// Когда nums[fast] !== 0 — меняем nums[slow] и nums[fast], slow++.
// Когда nums[fast] === 0 — только fast++ (ноль «перепрыгиваем»).
//
// После прохода: [ненули в начале][нули в хвосте]
//
// Сложность: O(n) время, O(1) доп. память.

// =============================================================================
// Условие задачи (LeetCode 283 — Move Zeroes)
// =============================================================================
//
// Дано:
//   - массив nums целых чисел
//
// Нужно:
//   - переместить все 0 в конец массива
//   - порядок ненулевых элементов сохранить
//   - изменить nums на месте (in-place), минимум доп. памяти
//
// Примеры:
//   [0, 1, 0, 3, 12]  →  [1, 3, 12, 0, 0]
//   [0]               →  [0]
//   [1, 2, 3]         →  [1, 2, 3]
//
// Паттерн по фреймворку выше: один массив + in-place → slow / fast
//
// =============================================================================

/**
 * @param {number[]} nums — изменяется на месте
 * @returns {number[]}
 */
function moveZeros(nums) {
  let slow = 0; // куда записать следующий ненулевой
  let fast = 0; // что сейчас смотрим

  while (fast < nums.length) {
    if (nums[fast] !== 0) {
      // нашли ненулевой — ставим его на позицию slow (swap)
      const temp = nums[slow];
      nums[slow] = nums[fast];
      nums[fast] = temp;
      slow++; // следующая «ячейка для записи» правее
    }
    // fast всегда двигается: обработали элемент на fast
    fast++;
  }

  return nums;
}


/**
 * @param {number[]} nums — изменяется на месте
 * @returns {number[]}
 */
function moveZeros(nums) {
  let slow = 0;
  let fast = 0;

  while (fast < nums.length) {
    if (nums[fast] !== 0) {
      const temp = nums[slow];
      nums[fast] = temp;
      nums[slow] = nums[fast];
      slow++;
    }
    fast++;
  }
}

// --- пример: каждый шаг для [0, 1, 0, 3, 12] ---
//
// старт:  nums = [0, 1, 0, 3, 12],  slow = 0,  fast = 0
//
// шаг 1 | fast = 0 | nums[0] = 0 → ноль, только fast++
//         nums = [0, 1, 0, 3, 12],  slow = 0,  fast = 1
//
// шаг 2 | fast = 1 | nums[1] = 1 → swap(slow=0, fast=1)
//         nums = [1, 0, 0, 3, 12],  slow = 1,  fast = 2
//
// шаг 3 | fast = 2 | nums[2] = 0 → ноль, только fast++
//         nums = [1, 0, 0, 3, 12],  slow = 1,  fast = 3
//
// шаг 4 | fast = 3 | nums[3] = 3 → swap(slow=1, fast=3)
//         nums = [1, 3, 0, 0, 12],  slow = 2,  fast = 4
//
// шаг 5 | fast = 4 | nums[4] = 12 → swap(slow=2, fast=4)
//         nums = [1, 3, 12, 0, 0],  slow = 3,  fast = 5
//
// fast >= length → конец, ответ: [1, 3, 12, 0, 0]
//
console.log(moveZeros([0, 1, 0, 3, 12])); // [1, 3, 12, 0, 0]

// --- slow / fast ---
//
//   fast — сканирует весь массив
//   slow — граница «уже собранных» ненулевых слева

module.exports = { moveZeros };

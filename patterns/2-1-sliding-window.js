// Паттерн: Скользящее окно — фиксированная длина k
//
// Суть: окно всегда из k элементов. Сдвиг: +nums[r] -nums[l], без пересчёта k раз.
//
// Когда узнаёшь задачу:
//   - явно дано k или «ровно k подряд»;
//   - макс./мин. сумма/среднее в окне длины k.
//
// Сложность: O(n) время, O(1) память.

// =============================================================================
// Условие задачи (идея LeetCode 643 — макс. среднее подмассива длины k)
// =============================================================================
//
// Дано:
//   - массив nums целых чисел
//   - число k — длина подряд идущего подмассива (окно фиксированного размера)
//
// Нужно вернуть:
//   - максимальную сумму среди всех подмассивов длины ровно k
//   (для LC 643: макс. среднее = эта сумма / k)
//
// Примеры:
//   nums = [2, 1, 5, 1, 3, 2],  k = 3
//   окна: [2,1,5]=8, [1,5,1]=7, [5,1,3]=9 ← max, [1,3,2]=6  →  ответ 9
//
//   nums = [1, 2, 3, 4],  k = 2  →  max(3, 5, 7) = 7
//
// Паттерн по фреймворку выше: окно фиксированной длины → этот файл (2-1)
//
// =============================================================================

/**
 * Максимальная сумма k подряд идущих элементов.
 *
 * @param {number[]} nums
 * @param {number} k — размер окна
 * @returns {number}
 */
function kElementsMaxSum(nums, k) {
  // 1. Первое окно: сумма nums[0 .. k-1]
  let windowSum = 0;
  for (let i = 0; i < k; i++) {
    windowSum += nums[i];
  }

  let maxSum = windowSum;

  // 2. Сдвигаем окно вправо: r — новый правый индекс, l — ушедший левый
  for (let r = k; r < nums.length; r++) {
    const l = r - k; // элемент, который выходит из окна
    windowSum = windowSum + nums[r] - nums[l];
    maxSum = Math.max(maxSum, windowSum);
  }

  return maxSum;
}


/**
 * Максимальная сумма k подряд идущих элементов.
 *
 * @param {number[]} nums
 * @param {number} k — размер окна
 * @returns {number}
 */
function kElementsMaxSum(nums, k) {
  let windowSum = 0;
  for (let i = 0; i < k; i++) {
    windowSum += nums[i];
  }

  let maxSum = windowSum;

  for (let r = k; r < nums.length; r++) {
    windowSum = windowSum + nums[r] - nums[r - k];
    maxSum = Math.max(maxSum, windowSum);
  }

  return maxSum;
}

// --- пример ---
//
//   nums = [2, 1, 5, 1, 3, 2], k = 3
//
// окно [2,1,5] → sum=8, max=8
// сдвиг: +1 -2 → [1,5,1] sum=7
// +3 -1 → [5,1,3] sum=9  ← max
// +2 -5 → [1,3,2] sum=6
//
console.log(kElementsMaxSum([2, 1, 5, 1, 3, 2], 3)); // 9

// --- визуально фиксированное окно ---
//
//   [ 2, 1, 5, 1, 3, 2 ]
//     [___]              k=3, старт
//        [___]           +nums[r] -nums[l]
//           [___]
//
// Наивно: для каждого i суммировать k элементов → O(n·k)
// Окно:   один проход → O(n)

module.exports = { kElementsMaxSum };

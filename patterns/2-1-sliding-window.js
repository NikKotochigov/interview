//                                   l/r, expand + shrink                 l/r, l = r+1 после отрезка
//
// Пересекающиеся: несколько ответов могут включать один элемент
//   (макс. подмассив, ≤ k нулей, min subarray sum ≥ S).
//
// Непересекающиеся: каждый элемент — в одном отрезке ответа

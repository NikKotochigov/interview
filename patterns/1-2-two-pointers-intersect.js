// =============================================================================
// Условие задачи (LeetCode 350 — Intersection of Two Arrays II)
// =============================================================================
//
// Дано:
//   - nums1, nums2 — два массива целых чисел, каждый отсортирован по возрастанию
//
// Нужно вернуть:
//   - массив пересечения: каждое значение, которое есть в ОБОИХ массивах,
//     столько раз, сколько оно встречается в обоих (минимум из двух частот)
//
// Примеры:
//   nums1 = [1, 2, 2, 3],  nums2 = [2, 2, 4]  →  [2, 2]
//   nums1 = [4, 9, 5],     nums2 = [9, 4, 9, 8, 4]  →  [4, 9]  (после sort)
//
// Ограничения для этого решения:
//   - оба массива уже отсортированы (иначе — хеш-счётчик, см. 3-1)
//
// =============================================================================

// Паттерн: два указателя — «каждому массиву по указателю» (см. фреймворк в 1-3)
//
// p1 по nums1, p2 по nums2, оба с начала, двигаем вперёд.
//
// Отличие от two-pointers.js (Two Sum II):
//   там l и r с противоположных концов одного массива;
//   здесь p1 и p2 идут по двум массивам в одну сторону (слева направо).
//
// Логика на каждом шаге:
//   nums1[p1] < nums2[p2]  → p1++  (в nums1 элемент меньше, его «догоняем»)
//   nums1[p1] > nums2[p2]  → p2++
//   равны                  → push в result, p1++, p2++
//
// Сложность: O(n + m) время, O(1) доп. память (без учёта result).

/**
 * Пересечение двух отсортированных массивов (все вхождения общих значений).
 *
 * @param {number[]} nums1 — отсортирован
 * @param {number[]} nums2 — отсортирован
 * @returns {number[]}
 */
function intersect(nums1, nums2) {
  let p1 = 0; // указатель по первому массиву
  let p2 = 0; // указатель по второму массиву
  const result = [];

  // пока оба указателя внутри своих массивов
  while (p1 < nums1.length && p2 < nums2.length) {
    if (nums1[p1] < nums2[p2]) {
      // в nums1 текущее число меньше — в nums2 такого «сейчас» нет, сдвигаем p1
      p1++;
    } else if (nums1[p1] > nums2[p2]) {
      // в nums2 меньше — сдвигаем p2
      p2++;
    } else {
      // совпадение — общий элемент
      result.push(nums1[p1]);
      p1++;
      p2++;
    }
  }

  return result;
}

// --- пример ---
//
//   nums1: [1, 2, 2, 3]
//           p1
//   nums2: [2, 2, 4]
//           p2
//
// шаг 1: 1 < 2  → p1=1
// шаг 2: 2 == 2 → result [2], p1=2, p2=1
// шаг 3: 2 == 2 → result [2,2], p1=3, p2=2
// шаг 4: 3 > 2  → p2=3, p2 вышел за массив → стоп
//
console.log(intersect([1, 2, 2, 3], [2, 2, 4])); // [2, 2]

// --- если массивы НЕ отсортированы ---
// этот код не подойдёт — нужен хеш-счётчик (частоты в nums2, проход по nums1).

module.exports = { intersect };

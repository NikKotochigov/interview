/**
 * Почему a[b] и a[c] «стирают» друг друга, если b и c — разные объекты
 *
 * У обычного объекта `{}` ключи свойств — только строки или Symbol.
 * Если написать a[b], ключ не остаётся «объектом b»: он приводится к строке
 * (ToPropertyKey). Для обычного объекта String(obj) === "[object Object]".
 *
 * Оба ключа b и c превращаются в одну и ту же строку "[object Object]",
 * поэтому второе присваивание перезаписывает первое.
 *
 * Для «ключей-объектов» используют Map / WeakMap или явные id / Symbol.
 */

const a = {};
const b = {};
const c = {};

a[b] = "1";
a[c] = "2";

// Один ключ "[object Object]", значение последнего присваивания:
// console.log(a); // { '[object Object]': '2' }
